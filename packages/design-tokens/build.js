#!/usr/bin/env node
/**
 * Design token codegen: tokens.json -> tokens.css (Web) + tokens.wxss (miniapp).
 *
 * Usage: node packages/design-tokens/build.js
 * Outputs are committed so consumers don't need a build step; regenerate and
 * commit whenever tokens.json changes.
 */
const fs = require('fs');
const path = require('path');

const here = __dirname;
const tokens = JSON.parse(fs.readFileSync(path.join(here, 'tokens.json'), 'utf-8'));

function flatten(obj, prefix = '') {
  const out = {};
  for (const [key, value] of Object.entries(obj)) {
    if (value && typeof value === 'object' && 'value' in value) {
      out[prefix + key] = value.value;
    } else if (value && typeof value === 'object') {
      Object.assign(out, flatten(value, `${prefix}${key}-`));
    }
  }
  return out;
}

function resolve(refs) {
  const resolved = {};
  for (const [key, value] of Object.entries(refs)) {
    if (typeof value === 'string' && value.startsWith('{') && value.endsWith('}')) {
      const target = value.slice(1, -1).replace(/\./g, '-');
      if (!(target in refs)) throw new Error(`Unknown token reference: ${value}`);
      resolved[key] = refs[target];
    } else {
      resolved[key] = value;
    }
  }
  return resolved;
}

const flat = flatten(tokens);

const cssNames = {};
for (const key of Object.keys(flat)) {
  cssNames[key] = `--dt-${key.replace(/^color-/, '').replace(/_/g, '-')}`;
}

const flatResolved = resolve(flat);

let css = '/* Generated by packages/design-tokens/build.js - do not edit by hand. */\n:root {\n';
for (const key of Object.keys(flat)) {
  if (key.startsWith('surface-pageDark') || key.startsWith('surface-cardDark')) continue;
  if (key.startsWith('typography-fontFamily')) continue;
  css += `  ${cssNames[key]}: ${flatResolved[key]};\n`;
}
css += '  --dt-font-family: Inter, "Microsoft YaHei", system-ui, -apple-system, sans-serif;\n';
css += '}\n\n[data-theme="dark"] {\n';
css += '  --dt-surface-page: #0b1220;\n';
css += '  --dt-surface-card: #151e2e;\n';
css += '  --dt-gray-900: #f9fafb;\n';
css += '  --dt-gray-700: #d1d5db;\n';
css += '  --dt-gray-500: #9ca3af;\n';
css += '  --dt-gray-300: #374151;\n';
css += '  --dt-gray-200: #1f2937;\n';
css += '  --dt-gray-100: #111827;\n';
css += '  --dt-gray-50: #0b1220;\n';
css += '}\n';
fs.writeFileSync(path.join(here, 'tokens.css'), css, 'utf-8');

// Miniapp WXSS: rpx units for spacing (750rpx design width).
let wxss = '/** Generated by packages/design-tokens/build.js - do not edit by hand. */\npage {\n';
for (const key of Object.keys(flat)) {
  if (key.startsWith('surface-pageDark') || key.startsWith('surface-cardDark')) continue;
  if (key.startsWith('typography-fontFamily')) continue;
  let value = flatResolved[key];
  value = value.replace(/(\d+)px/g, (match, num) => `${Number(num) * 2}rpx`);
  const name = `--dt-${key.replace(/^color-/, '').replace(/_/g, '-')}`;
  wxss += `  ${name}: ${value};\n`;
}
wxss += '  --dt-font-family: Inter, "Microsoft YaHei", system-ui, -apple-system, sans-serif;\n';
wxss += '}\n';
const miniappOut = path.join(here, '..', '..', 'miniapp-wechat', 'styles', 'tokens.wxss');
fs.mkdirSync(path.dirname(miniappOut), { recursive: true });
fs.writeFileSync(miniappOut, wxss, 'utf-8');

// Web copy for direct import without workspace plumbing.
fs.copyFileSync(path.join(here, 'tokens.css'), path.join(here, '..', '..', 'apps', 'techgroup-enterprise-travel-web', 'src', 'tokens.css'));

console.log('design tokens generated: tokens.css, tokens.wxss, web/src/tokens.css');
